/// Déquantifie un bloc **IQ3_XXS** (98 octets, 256 poids).
///
/// Structure : 2 octets d'échelle `d`, 64 octets d'index de grille (huit par
/// sous-bloc de 32 poids, deux par groupe de 8), puis 32 octets qui portent à
/// la fois **4 bits d'échelle** (les quatre derniers) et **quatre paquets de
/// signes de 7 bits** — il n'y a pas de tableau d'échelles séparé, contrairement
/// à IQ2_XXS où les deux vivent dans le même `u16` de poids fort.
///
/// `x = d · (0,5 + échelle) · 0,5 · grille · signe`
///
/// C'est le type de 30 % des poids de Kimi-K2.7, GLM-5.3 et V4-Flash : sans lui,
/// aucun de ces trois modèles ne se charge.
pub fn dequant_iq3xxs_dans(bloc: &[u8], out: &mut [f32]) {
    assert!(bloc.len() >= 98, "bloc IQ3_XXS trop court : {}", bloc.len());
    let d = crate::gguf::Gguf::f16_to_f32(u16::from_le_bytes([bloc[0], bloc[1]]));
    let qs = &bloc[2..98];
    let ech = &qs[64..96];
    assert!(out.len() >= 256, "tampon de sortie trop court : {}", out.len());
    for ib32 in 0..8usize {
        let aux = u32::from_le_bytes([ech[4 * ib32], ech[4 * ib32 + 1],
                                      ech[4 * ib32 + 2], ech[4 * ib32 + 3]]);
        let db = d * (0.5 + ((aux >> 28) as f32)) * 0.5;
        for l in 0..4usize {
            let signes = KSIGNS_IQ2XS[((aux >> (7 * l)) & 127) as usize];
            let g1 = IQ3XXS_GRID[qs[8 * ib32 + 2 * l] as usize];
            let g2 = IQ3XXS_GRID[qs[8 * ib32 + 2 * l + 1] as usize];
            for j in 0..4usize {
                let s1 = if signes & (1u8 << j) != 0 { -1.0 } else { 1.0 };
                let s2 = if signes & (1u8 << (j + 4)) != 0 { -1.0 } else { 1.0 };
                out[ib32 * 32 + l * 8 + j] = db * g1[j] as f32 * s1;
                out[ib32 * 32 + l * 8 + j + 4] = db * g2[j] as f32 * s2;
            }
        }
    }
    
}

