/// `IQ1S_DELTA` de ggml : le décalage appliqué à chaque niveau de la grille.
const IQ1S_DELTA: f32 = 0.125;

/// Déquantifie un bloc **IQ1_M** (56 octets, 256 poids).
///
/// Structure : 8 octets d'échelles entrelacées, 32 octets d'index de grille (les
/// 8 bits bas), 16 octets de bits hauts d'index **et** de bits de décalage.
/// Trois bits d'échelle par sous-bloc de 16, un bit de signe du décalage.
///
/// `x = d·(2·e+1)·(grille + ±0,125)`
pub fn dequant_iq1m(bloc: &[u8]) -> Vec<f32> {
    assert!(bloc.len() >= 56, "bloc IQ1_M trop court : {}", bloc.len());
    // L'ORDRE des champs est `qs[32]`, `qh[16]`, `scales[8]` — les échelles sont
    // EN DERNIER. Les lire en premier donnait une échelle absurde et un écart de
    // 2,4e5 : c'est la comparaison avec ggml qui l'a montré.
    let sc: [u16; 4] = [
        u16::from_le_bytes([bloc[48], bloc[49]]),
        u16::from_le_bytes([bloc[50], bloc[51]]),
        u16::from_le_bytes([bloc[52], bloc[53]]),
        u16::from_le_bytes([bloc[54], bloc[55]]),
    ];
    // L'échelle f16 est répartie dans les quatre mots : 4 bits de chacun.
    let brut = (sc[0] >> 12) | ((sc[1] >> 8) & 0x00f0) | ((sc[2] >> 4) & 0x0f00)
             | (sc[3] & 0xf000);
    let d = crate::gguf::Gguf::f16_to_f32(brut);
    let qs = &bloc[0..32];
    let qh = &bloc[32..48];
    let mut out = vec![0f32; 256];
    for ib in 0..8usize {
        let dl1 = d * (2 * ((sc[ib / 2] >> (6 * (ib % 2))) & 0x7) + 1) as f32;
        let dl2 = d * (2 * ((sc[ib / 2] >> (6 * (ib % 2) + 3)) & 0x7) + 1) as f32;
        let q = &qs[4 * ib..4 * ib + 4];
        let (h0, h1) = (qh[2 * ib], qh[2 * ib + 1]);
        let idx = [
            q[0] as u16 | ((h0 as u16) << 8 & 0x700),
            q[1] as u16 | ((h0 as u16) << 4 & 0x700),
            q[2] as u16 | ((h1 as u16) << 8 & 0x700),
            q[3] as u16 | ((h1 as u16) << 4 & 0x700),
        ];
        let delta = [
            if h0 & 0x08 != 0 { -IQ1S_DELTA } else { IQ1S_DELTA },
            if h0 & 0x80 != 0 { -IQ1S_DELTA } else { IQ1S_DELTA },
            if h1 & 0x08 != 0 { -IQ1S_DELTA } else { IQ1S_DELTA },
            if h1 & 0x80 != 0 { -IQ1S_DELTA } else { IQ1S_DELTA },
        ];
        for l in 0..4usize {
            let grille = IQ1S_GRID[idx[l] as usize];
            let dl = if l < 2 { dl1 } else { dl2 };
            for j in 0..8usize {
                out[ib * 32 + l * 8 + j] = dl * (grille[j] as f32 + delta[l]);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn iq2xxs_taille_et_plausibilite() {
        let mut bloc = vec![0u8; 66];
        // d = 1,0 en f16.
        bloc[0] = 0x00; bloc[1] = 0x3C;
        let v = dequant_iq2xxs(&bloc);
        assert_eq!(v.len(), 256);
        // Toutes les entrées de grille sont non nulles, donc aucun poids ne doit
        // l'être : une grille mal extraite donnerait des zéros.
        assert!(v.iter().all(|x| x.is_finite()), "valeurs non finies");
        assert!(v.iter().any(|x| *x != 0.0), "tous les poids sont nuls");
        // Les deux tables doivent avoir la bonne taille.
        assert_eq!(IQ2XXS_GRID.len(), 256);
        assert_eq!(KSIGNS_IQ2XS.len(), 128);
    }
}
