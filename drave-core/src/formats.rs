/// Déquantifie un bloc **IQ4_XS** (136 octets, 256 poids) : 2 octets d'échelle,
/// 2 octets d'échelles hautes, 4 octets d'échelles basses et 128 octets de
/// quants 4 bits.
///
/// Les **16 échelles de 6 bits** sont éclatées : 4 bits dans `scales_l` (un
/// octet pour deux sous-blocs), 2 bits dans `scales_h`. Chaque nibble est un
/// **index** dans la table `kvalues_iq4nl` (−127 … 113), pas une valeur : c'est
/// une quantification non linéaire, et la lire comme un entier 4 bits donne des
/// poids faux d'un facteur qui dépend du niveau.
pub fn dequant_iq4xs_dans(bloc: &[u8], out: &mut [f32]) {
    assert!(bloc.len() >= 136, "bloc IQ4_XS trop court : {}", bloc.len());
    let d = crate::gguf::Gguf::f16_to_f32(u16::from_le_bytes([bloc[0], bloc[1]]));
    let scales_h = u16::from_le_bytes([bloc[2], bloc[3]]);
    let scales_l = &bloc[4..8];
    let qs = &bloc[8..136];
    assert!(out.len() >= 256, "tampon de sortie trop court : {}", out.len());
    for ib in 0..8usize {
        let ls = (((scales_l[ib / 2] >> (4 * (ib % 2))) & 0x0F) as i32
                  | ((((scales_h >> (2 * ib)) & 3) as i32) << 4)) - 32;
        let dl = d * ls as f32;
        for j in 0..16usize {
            let octet = qs[16 * ib + j];
            out[32 * ib + j] = dl * KVALS_IQ4NL[(octet & 0x0F) as usize] as f32;
            out[32 * ib + j + 16] = dl * KVALS_IQ4NL[(octet >> 4) as usize] as f32;
        }
    }
    
}

/// Version qui alloue : pour les appelants qui veulent un `Vec` (outils, tests).
pub fn dequant_iq4xs(bloc: &[u8]) -> Vec<f32> {
    let mut v = vec![0f32; 256];
    dequant_iq4xs_dans(bloc, &mut v);
    v
}

/// Déquantifie un bloc **IQ1_S** (50 octets, 256 poids).
///
/// Structure : 2 octets d'échelle `d`, 32 octets d'index de grille, puis 16
/// `u16` qui portent chacun **trois bits d'index supplémentaires** (par groupes
/// de huit poids), **trois bits d'échelle** et **un bit de signe du décalage**.
/// D'où `x = d · (2·k + 1) · (grille ± 0,125)` avec `k ∈ 0..7`.
///
/// C'est le type de 42 à 45 % des poids de GLM-5.3 et GLM-5.3-Flash.
pub fn dequant_iq1s_dans(bloc: &[u8], out: &mut [f32]) {
    assert!(bloc.len() >= 50, "bloc IQ1_S trop court : {}", bloc.len());
    let d = crate::gguf::Gguf::f16_to_f32(u16::from_le_bytes([bloc[0], bloc[1]]));
    let qs = &bloc[2..34];
    assert!(out.len() >= 256, "tampon de sortie trop court : {}", out.len());
    for ib in 0..8usize {
        let qh = u16::from_le_bytes([bloc[34 + 2 * ib], bloc[34 + 2 * ib + 1]]);
        let dl = d * (2.0 * ((qh >> 12) & 7) as f32 + 1.0);
        let delta = if qh & 0x8000 != 0 { -IQ1S_DELTA } else { IQ1S_DELTA };
        for l in 0..4usize {
            let index = (qs[4 * ib + l] as usize) | ((((qh >> (3 * l)) & 7) as usize) << 8);
            let grille = IQ1S_GRID[index];
            for j in 0..8usize {
                out[ib * 32 + l * 8 + j] = dl * (grille[j] as f32 + delta);
            }
        }
    }
    
}

/// Version qui alloue : pour les appelants qui veulent un `Vec` (outils, tests).
pub fn dequant_iq1s(bloc: &[u8]) -> Vec<f32> {
    let mut v = vec![0f32; 256];
    dequant_iq1s_dans(bloc, &mut v);
    v
}

/// Déquantifie un bloc **IQ2_XXS** (66 octets, 256 poids).
///
/// Structure : 2 octets d'échelle `d`, puis 32 `u16`. Les 8 octets d'un
/// sous-bloc de 32 poids portent quatre index de grille (un par `u8`) et quatre
/// paquets de signes de 7 bits, plus 4 bits d'échelle dans le mot de poids fort.
///
/// `x = d · (0,5 + échelle) · 0,25 · grille · signe`
pub fn dequant_iq2xxs_dans(bloc: &[u8], out: &mut [f32]) {
    assert!(bloc.len() >= 66, "bloc IQ2_XXS trop court : {}", bloc.len());
    let d = crate::gguf::Gguf::f16_to_f32(u16::from_le_bytes([bloc[0], bloc[1]]));
    assert!(out.len() >= 256, "tampon de sortie trop court : {}", out.len());
    for ib32 in 0..8usize {
        // ATTENTION : dans ggml, `qs` est un `uint16_t[32]`, donc `qs + 4*ib32`
        // avance de 4 × 2 = 8 OCTETS. Écrire `2 + 4*ib32` octets laissait le
        // premier sous-bloc juste et tous les suivants faux — c'est la
        // comparaison avec ggml qui l'a montré, pas la lecture.
        let aux = &bloc[2 + 8 * ib32..2 + 8 * ib32 + 8];
        let bas = u32::from_le_bytes([aux[0], aux[1], aux[2], aux[3]]);
        let haut = u32::from_le_bytes([aux[4], aux[5], aux[6], aux[7]]);
        let db = d * (0.5 + ((haut >> 28) as f32)) * 0.25;
        let index = bas.to_le_bytes();
        for l in 0..4usize {
            let grille = IQ2XXS_GRID[index[l] as usize];
            let signes = KSIGNS_IQ2XS[((haut >> (7 * l)) & 127) as usize];
            for j in 0..8usize {
                // `kmask_iq2xs[j]` vaut `1 << j` : le bit de signe du niveau j.
                let s = if signes & (1u8 << j) != 0 { -1.0 } else { 1.0 };
                out[ib32 * 32 + l * 8 + j] = db * grille[j] as f32 * s;
            }
        }
    }
    
}

